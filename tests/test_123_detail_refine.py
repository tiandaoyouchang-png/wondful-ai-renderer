FIT = {"scale": 1.0, "scale_x": 1.0, "scale_y": 1.0, "dx": 0.0, "dy": 0.0}

H, W = 360, 640
yy, xx = np.mgrid[0:H, 0:W]
PROD = (((xx - 320) / 280.0) ** 2 + ((yy - 180) / 150.0) ** 2 <= 1).astype(np.float32)


def plate_at(cx, cy, hw=26, hh=10):
    plate = (np.abs(xx - cx) < hw) & (np.abs(yy - cy) < hh)
    letters = plate & (np.abs(yy - cy) < hh // 2) & ((xx // 3) % 3 == 0) & (np.abs(xx - cx) < hw - 4)
    return plate, letters


def scene(plates, letters_in_ai):
    """AI image (grainy, lit) with plates; ``letters_in_ai[i]`` False = that plate is blank in the
    AI image. Detail pass: flat light, sharp letters on every plate. Keep mask = plates."""
    rng = np.random.default_rng(3)
    ai = np.full((H, W, 3), 0.45, np.float32)
    ai[PROD > 0] = (0.25, 0.5, 0.3)
    ai += (0.008 * rng.standard_normal((H, W)))[..., None].astype(np.float32)
    det = np.zeros((H, W, 4), np.float32)
    det[..., :3] = (0.3, 0.55, 0.35)
    det[..., 3] = PROD
    keep = np.zeros((H, W, 4), np.float32)
    for (plate, letters), ok in zip(plates, letters_in_ai):
        ai[plate] = 0.85
        if ok:
            ai[letters] = 0.12
        det[plate, :3] = 0.9
        det[letters, :3] = 0.05
        keep[plate, 0] = 1
        keep[plate, 3] = 1
    return np.clip(ai, 0, 1).astype(np.float32), det, keep


def good_fix(calls):
    """Mock image model that draws the reference's letters in the AI crop's own lighting."""
    def fn(base, ref, out, size, prompt_fn):
        calls.append({"base": base, "ref": ref, "out": out, "size": size, "prompt": prompt_fn()})
        b = PNG.read_png(base)[..., :3].astype(np.float32) / 255
        r = PNG.read_png(ref)[..., :3].astype(np.float32) / 255
        lb, lr = LO.luminance(b), LO.luminance(r)
        o = np.where(((lr < 0.25) & (lb > 0.6))[..., None], b * 0.15, b)
        PNG.write_png(out, (np.clip(o, 0, 1) * 255 + 0.5).astype(np.uint8))
        return out
    return fn


def copy_fix(calls, transform=None):
    def fn(base, ref, out, size, prompt_fn):
        calls.append({"base": base, "ref": ref, "size": size})
        b = PNG.read_png(base)[..., :3].astype(np.float32) / 255
        if transform is not None:
            b = transform(b)
        PNG.write_png(out, (np.clip(b, 0, 1) * 255 + 0.5).astype(np.uint8))
        return out
    return fn


def run(ai, det, keep, fn, **kw):
    d = kw.pop("work_dir", None) or tempfile.mkdtemp()
    return DR.refine_details(ai, det, PROD, keep, fit=FIT, edit_fn=fn, work_dir=d, **kw), d



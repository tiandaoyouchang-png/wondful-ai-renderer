def _translator(report=False):
    # Keep this module importable by offline tools; bpy is only needed at display time.
    try:
        import bpy
        translations = bpy.app.translations
        return getattr(translations, 'pgettext_rpt', translations.pgettext_iface) if report else translations.pgettext_iface
    except (ImportError, AttributeError):
        return lambda text: text


def _message_patterns():
    import re
    from string import Formatter

    patterns = []
    for (context, source), english in TRANSLATIONS['en_US'].items():
        if context != DEFAULT or not re.search(r'\{v\d+\}', source):
            continue
        parts = list(Formatter().parse(source))
        # Full-message templates only, never substring replacement in user data.
        fragments = []
        for literal, field, _spec, _conversion in parts:
            fragments.append(re.escape(literal))
            if field:
                value = r'[-+]?\d+(?:\.\d+)?' if field in _NUMERIC_FIELDS.get(source, ()) else '.*?'
                fragments.append(f'(?P<{field}>{value})')
        pattern = ''.join(fragments)
        literal_size = sum(len(literal) for literal, *_rest in parts)
        patterns.append((literal_size, re.compile(pattern, re.DOTALL), source))
    return tuple((pattern, source) for _size, pattern, source in sorted(patterns, key=lambda p: -p[0]))


_PATTERNS = None


def translate_message(text, *, report=False, translator=None, _depth=0):
    """Localize a *status/diagnostic*, leaving canonical pipeline state untouched.

    Older .blend files and workers store already-formatted Chinese status strings.
    Match only whole catalog templates to display those messages. Captured names,
    paths, IDs and model/user text stay opaque; only explicitly listed message fields
    recurse. Call before wrapping/truncating. Never use this on editable prompt text.
    ``translator`` permits offline testing without Blender or process-global mocks.
    """
    global _PATTERNS
    if not text or _depth > 12:
        return text
    translate = translator if translator is not None else _translator(report)
    # Respect Blender's interface/report translation switches and Chinese fallback.
    if translate('连接') == '连接':
        return text
    result = translate(text)
    if result != text:
        return result
    if text.startswith(' · '):
        translated_part = translate(text[3:])
        if translated_part != text[3:]:
            return ' · ' + translated_part
    if _PATTERNS is None:
        _PATTERNS = _message_patterns()
    for pattern, source in _PATTERNS:
        match = pattern.fullmatch(text)
        if match is None:
            continue
        translated = translate(source)
        if translated == source:
            continue
        values = match.groupdict()
        for key in _MESSAGE_FIELDS.get(source, ()):
            values[key] = translate_message(values[key], translator=translate, _depth=_depth + 1)
        return translated.format(**values)
    for pattern, source in _PATTERNS:
        if not _NUMERIC_FIELDS.get(source) and source != '（回贴后 {v0}）':
            continue
        # A complete numeric clause may have another known status appended.
        if not source.endswith('}'):
            match = pattern.match(text)
            if match and 0 < match.end() < len(text) and text[match.end()] in ' ·（；':
                left = translate_message(match.group(), translator=translate, _depth=_depth + 1)
                right = translate_message(text[match.end():], translator=translate, _depth=_depth + 1)
                if left != match.group() or right != text[match.end():]:
                    return left + right
        # Optional numeric clauses such as a reference-cap warning follow a
        # protected name/count clause. Only a literal prefix may delimit them.
        if not source.startswith('{'):
            for match in pattern.finditer(text):
                if match.start() > 0 and match.end() == len(text):
                    left = translate_message(text[:match.start()], translator=translate, _depth=_depth + 1)
                    right = translate_message(match.group(), translator=translate, _depth=_depth + 1)
                    if left != text[:match.start()] or right != match.group():
                        return left + right
    for affix in _MESSAGE_AFFIXES:
        translated = translate(affix)
        if translated == affix:
            continue
        if text.startswith(affix):
            if affix == ' · 重试：':
                # This summary alone contains camera-name(reason-list) records.
                # Keep each camera name opaque and localize only its known reasons.
                records = []
                for record in text[len(affix):].split('；'):
                    name, marker, reasons = record.rpartition('（')
                    if marker and reasons.endswith('）'):
                        reasons = ', '.join(translate_message(reason, translator=translate, _depth=_depth + 1)
                                            for reason in reasons[:-1].split('、'))
                        records.append(name + ' (' + reasons + ')')
                    else:
                        records.append(record)
                return translated + '; '.join(records)
            return translated + translate_message(text[len(affix):], translator=translate, _depth=_depth + 1)
        if text.endswith(affix):
            return translate_message(text[:-len(affix)], translator=translate, _depth=_depth + 1) + translated
    # Status summaries are composed with this explicit separator. Preserve all
    # unknown fragments, including external diagnostics, verbatim.
    import re
    parts = re.split(r'(?= · )', text)
    if len(parts) > 1 and parts[0]:
        return ''.join(translate_message(part, translator=translate, _depth=_depth + 1)
                       for part in parts)
    return text
